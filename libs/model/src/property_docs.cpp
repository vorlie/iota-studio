const PropertyDoc* findPropertyDoc(ElementType ownerType, std::string_view rawKey) noexcept {
  for (const auto& ov : kElementPropertyOverrides) {
    if (ov.owner == ownerType && eqIgnoreCase(ov.doc.rawKey, rawKey)) {
      return &ov.doc;
    }
  }
  for (const auto& doc : kSharedPropertyDocs) {
    if (eqIgnoreCase(doc.rawKey, rawKey)) {
      return &doc;
    }
  }
  return nullptr;
}

std::string formatPropertyDisplayName(ElementType ownerType, std::string_view rawKey) {
  if (const PropertyDoc* doc = findPropertyDoc(ownerType, rawKey)) {
    return std::string(doc->displayName);
  }
  return titleCaseIdentifier(rawKey);
}

const GroupDoc* findGroupDoc(std::string_view rawGroupTag) noexcept {
  for (const auto& g : kGroupDocs) {
    if (eqIgnoreCase(g.rawTag, rawGroupTag)) {
      return &g;
    }
  }
  return nullptr;
}

std::string formatGroupDisplayName(std::string_view rawGroupTag) {
  if (const GroupDoc* g = findGroupDoc(rawGroupTag)) {
    return std::string(g->displayName);
  }
  return titleCaseIdentifier(rawGroupTag);
}

const ElementDoc& getElementDoc(ElementType type) noexcept {
  const auto& docs = buildElementDocs();
  for (const auto& d : docs) {
    if (d.type == type) {
      return d;
    }
  }
  static constexpr ElementDoc kFallback{
      ElementType::Unknown,
      "Element",
      "General",
      "Scene element rendered inside the active composition.",
      "Inspect properties below to customize appearance and audio reactivity.",
  };
  return kFallback;
}

const std::vector<ElementDoc>& allElementDocs() noexcept {
  return buildElementDocs();
}

const MVarModeDoc* findMVarModeDoc(std::string_view mode) noexcept {
  const auto& modes = buildMVarModeDocs();
  for (const auto& m : modes) {
    if (eqIgnoreCase(m.mode, mode)) {
      return &m;
    }
  }
  return nullptr;
}

const std::vector<MVarModeDoc>& allMVarModeDocs() noexcept {
  return buildMVarModeDocs();
}

const std::vector<TextTokenDoc>& allTextTokenDocs() noexcept {
  return buildTextTokenDocs();
}

