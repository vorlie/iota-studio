bool eqIgnoreCase(std::string_view a, std::string_view b) noexcept {
  if (a.size() != b.size()) return false;
  for (size_t i = 0; i < a.size(); ++i) {
    if (std::tolower(static_cast<unsigned char>(a[i])) !=
        std::tolower(static_cast<unsigned char>(b[i]))) {
      return false;
    }
  }
  return true;
}

std::string titleCaseIdentifier(std::string_view raw) {
  while (!raw.empty() && raw.front() == '_') {
    raw.remove_prefix(1);
  }
  if (raw.size() >= 2 && std::isdigit(static_cast<unsigned char>(raw[0])) && raw[1] == '_') {
    raw.remove_prefix(2);
  }
  if (raw.empty()) {
    return "Misc";
  }

  std::string out;
  out.reserve(raw.size() + 8);
  bool newWord = true;
  char prev = '\0';
  for (size_t i = 0; i < raw.size(); ++i) {
    const unsigned char uc = static_cast<unsigned char>(raw[i]);
    const char c = static_cast<char>(uc);
    if (c == '_' || c == '-') {
      if (!out.empty() && out.back() != ' ') out.push_back(' ');
      newWord = true;
      prev = c;
      continue;
    }
    const bool isUpper = std::isupper(uc) != 0;
    const bool isDigit = std::isdigit(uc) != 0;
    const bool prevLower = prev != '\0' && std::islower(static_cast<unsigned char>(prev)) != 0;
    const bool prevDigit = prev != '\0' && std::isdigit(static_cast<unsigned char>(prev)) != 0;
    const bool nextLower =
        (i + 1 < raw.size()) && std::islower(static_cast<unsigned char>(raw[i + 1])) != 0;

    if (!out.empty() && out.back() != ' ') {
      if ((isUpper && (prevLower || nextLower)) || (isDigit && !prevDigit) ||
          (std::isalpha(uc) && prevDigit)) {
        out.push_back(' ');
        newWord = true;
      }
    }
    out.push_back(newWord ? static_cast<char>(std::toupper(uc)) : c);
    newWord = false;
    prev = c;
  }
  return out;
}

